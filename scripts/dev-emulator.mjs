import { spawn } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }
  const out = {};
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const i = trimmed.indexOf("=");
    if (i === -1) {
      continue;
    }
    out[trimmed.slice(0, i).trim()] = trimmed.slice(i + 1).trim();
  }
  return out;
}

const root = resolve(import.meta.dirname, "..");
const emulatorFile = resolve(root, ".env.emulator");
const emulatorVars = loadEnvFile(emulatorFile);

// Next only reliably inlines NEXT_PUBLIC_* from .env* files into the
// browser bundle. Mirror emulator config into .env.development.local.
const devLocal = resolve(root, ".env.development.local");
const banner =
  "# Generated by scripts/dev-emulator.mjs — do not commit. Overrides production .env.local for local emulator runs.\n";
writeFileSync(
  devLocal,
  banner +
    Object.entries(emulatorVars)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n",
  "utf8",
);
console.log("[payround] wrote", devLocal);

const env = {
  ...process.env,
  ...emulatorVars,
};

const port = process.env.PORT || "3002";
const child = spawn("npx", ["next", "dev", "-p", port], {
  cwd: root,
  env,
  stdio: "inherit",
  shell: true,
});

child.on("exit", (code) => process.exit(code ?? 0));
