import { spawn, execSync } from "node:child_process";
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }
  const out = {};
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const i = trimmed.indexOf("=");
    if (i === -1) {
      continue;
    }
    out[trimmed.slice(0, i).trim()] = trimmed.slice(i + 1).trim();
  }
  return out;
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function waitForUrl(url, attempts = 60) {
  for (let i = 0; i < attempts; i++) {
    try {
      const res = await fetch(url);
      if (res.ok || res.status === 404 || res.status === 400) {
        return;
      }
    } catch {
      // retry
    }
    await sleep(2000);
  }
  throw new Error(`Timeout waiting for ${url}`);
}

function run(cmd, opts = {}) {
  console.log(">", cmd);
  execSync(cmd, {
    cwd: root,
    stdio: "inherit",
    shell: true,
    ...opts,
  });
}

const emulatorEnv = loadEnvFile(resolve(root, ".env.emulator"));
writeFileSync(
  resolve(root, ".env.development.local"),
  "# Generated by scripts/run-e2e-emulator.mjs\n" +
    Object.entries(emulatorEnv)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n",
  "utf8",
);

const env = {
  ...process.env,
  ...emulatorEnv,
  PLAYWRIGHT_USE_EMULATOR: "true",
  // Prefer 3002 — local `npm run dev` often already owns 3001.
  PLAYWRIGHT_PORT: process.env.PLAYWRIGHT_PORT || "3002",
  PLAYWRIGHT_BASE_URL:
    process.env.PLAYWRIGHT_BASE_URL || "http://127.0.0.1:3002",
  FIRESTORE_EMULATOR_HOST: "127.0.0.1:8181",
  FIREBASE_AUTH_EMULATOR_HOST: "127.0.0.1:9099",
  FIREBASE_STORAGE_EMULATOR_HOST: "127.0.0.1:9199",
  GCLOUD_PROJECT: "demo-payround",
  NEXT_PUBLIC_APP_URL:
    process.env.PLAYWRIGHT_BASE_URL || "http://127.0.0.1:3002",
};

const nextPort = env.PLAYWRIGHT_PORT;

let nextProc = null;

try {
  console.log("\n=== 1) Start Firebase emulators (Docker) ===");
  run("docker compose -f docker-compose.emulators.yml up -d");

  console.log("\n=== 2) Wait for Firestore + Storage emulators ===");
  await waitForUrl("http://127.0.0.1:8181");
  // Storage responds with 404/400/200 on root; any response means it's up.
  await waitForUrl("http://127.0.0.1:9199");

  console.log("\n=== 3) Seed owner + member + Netflix Shared ===");
  run("node scripts/seed-emulator.mjs", { env });

  console.log(`\n=== 4) Start Next.js on :${nextPort} with emulator env ===`);
  nextProc = spawn("npx", ["next", "dev", "-p", nextPort], {
    cwd: root,
    env,
    stdio: "inherit",
    shell: true,
  });

  await waitForUrl(`http://127.0.0.1:${nextPort}`);

  console.log("\n=== 5) Playwright (smoke + invite + proof upload) ===");
  run(
    "npx playwright test --project=chromium e2e/smoke.spec.ts e2e/member-invite.emulator.spec.ts e2e/invite-accept.emulator.spec.ts e2e/proof-upload.emulator.spec.ts",
    { env },
  );

  console.log("\n✅ Emulator E2E passed");
} catch (e) {
  console.error("\n❌ Emulator E2E failed", e);
  process.exitCode = 1;
} finally {
  if (nextProc && !nextProc.killed) {
    nextProc.kill("SIGTERM");
  }
}
